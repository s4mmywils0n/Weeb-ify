-- -----------------------------------------------------------------------------
-- anime: one row per anime, loaded from the Kitsu API by database/db.php,
-- genres filled in afterwards by database/Category.php
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.anime (
    id                serial       PRIMARY KEY,
    anime_id          varchar(255) UNIQUE,          -- Kitsu's id for this anime
    slug              varchar(255),
    image             text,
    title             text,
    synopsis          text,
    age_rating        varchar(50),
    created_at        timestamp,                    -- when Kitsu added it, not when we did
    end_date          timestamp,
    episode_count     integer,
    popularity_rank   integer,
    show_type         varchar(50),
    status            varchar(50),
    kitsu_url         text,
    genres            text[]                        -- e.g. {Action,Comedy}
);

-- -----------------------------------------------------------------------------
-- user: accounts created by the /register page (app/models/AccountModel.php)
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public."user" (
    id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name    varchar NOT NULL,
    username      varchar NOT NULL UNIQUE,
    email         varchar NOT NULL UNIQUE,
    "phoneNumber" varchar,
    password      varchar NOT NULL,                 -- password_hash() output, never plain text
    "createdAt"   timestamp,
    is_admin      boolean DEFAULT false
);

-- -----------------------------------------------------------------------------
-- favorites: anime a user has saved
-- NOTE: the live table has NO foreign keys (user_id -> "user".id and
-- anime_id -> anime.anime_id are not enforced). Kept as-is here so this file
-- matches the real database.
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS public.favorites (
    id            bigserial    PRIMARY KEY,
    user_id       bigint       NOT NULL,
    anime_id      varchar(255) NOT NULL,            -- matches anime.anime_id (Kitsu id)
    url           text,
    image         text,
    episode_count integer,
    airing        boolean,
    show_type     varchar(50),
    created_at    timestamp    NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (user_id, anime_id)
);

CREATE INDEX IF NOT EXISTS idx_favorites_anime_id ON public.favorites (anime_id);
CREATE INDEX IF NOT EXISTS idx_favorites_user_id  ON public.favorites (user_id);

-- -----------------------------------------------------------------------------
-- Row Level Security (Supabase). These only affect requests that go through
-- Supabase's own REST API with the anon/publishable key. The PHP app connects
-- as the database owner, so it is not limited by them.
-- -----------------------------------------------------------------------------
ALTER TABLE public.anime     ENABLE ROW LEVEL SECURITY;
ALTER TABLE public."user"    ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.favorites ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Signed-out Access" ON public.anime
    FOR SELECT TO anon USING (true);

-- WARNING: lets anyone with the publishable key insert/update/delete anime.
-- Marked TEMP in the live database; remove before Build 3 (security).
CREATE POLICY "TEMP FULL ACCESS" ON public.anime
    FOR ALL TO anon USING (true) WITH CHECK (true);

